export async function getSelfHealingPromptState(context: vscode.ExtensionContext): Promise<SelfHealingPromptState> {
	const copilotInstalled = isCopilotInstalled();
	return {
		selfHealingEnabled: isSelfHealingEnabled(),
		copilotInstalled,
		pluginInstalled: copilotInstalled && (await isCxDevAssistPluginAvailable({ userDataDir: getVsCodeUserDataDir(context) })),
		dismissed: context.globalState.get<boolean>(constants.getSelfHealingDontShowAgainKey(), false) === true,
		shownThisSession,
	};
}

/** Shows at most one install message per session, only while Self-Healing is ON. Never throws. */
export async function maybeShowSelfHealingPrompt(context: vscode.ExtensionContext): Promise<SelfHealingPrompt> {
	try {
		const prompt = decideSelfHealingPrompt(await getSelfHealingPromptState(context));
		if (!prompt) {
			return undefined;
		}
		shownThisSession = true;
		void vscode.window
			.showInformationMessage(selfHealingMessages.installCopilot, selfHealingMessages.installCopilotButton, selfHealingMessages.dontShowAgainButton)
			.then(async selection => {
				try {
					if (selection === selfHealingMessages.dontShowAgainButton) {
						await context.globalState.update(constants.getSelfHealingDontShowAgainKey(), true);
					} else if (selection === selfHealingMessages.installCopilotButton) {
						await vscode.commands.executeCommand("extension.open", constants.copilotChatExtensionId);
					}
				} catch (error) {
					currentLogs?.warn(`Self-Healing prompt action failed: ${error instanceof Error ? error.message : String(error)}`);
				}
			});
		return prompt;
	} catch (error) {
		currentLogs?.warn(`Self-Healing prompt failed: ${error instanceof Error ? error.message : String(error)}`);
		return undefined;
	}
}

/**
 * Called when the user turns Self-Healing ON. Other editors (Cursor, Windsurf, ...) are told it is not supported.
 * In VS Code the cx-devassist plugin is checked: installed shows the ready message, missing shows a popup with
 * install and documentation buttons. Never throws.
 */
export async function onSelfHealingTurnedOn(context: vscode.ExtensionContext, logs?: Logs, appName: string = vscode.env?.appName ?? ""): Promise<void> {
	try {
		if (!isSelfHealingSupportedHost(appName)) {
			void vscode.window.showInformationMessage(`${selfHealingMessages.unsupportedEditor} (${appName})`);
			return;
		}
		if (await isCxDevAssistPluginAvailable({ userDataDir: getVsCodeUserDataDir(context) })) {
			void vscode.window.showInformationMessage(selfHealingMessages.pluginReady);
			return;
		}
		void vscode.window
			.showInformationMessage(selfHealingMessages.pluginNeeded, selfHealingMessages.installPluginButton, selfHealingMessages.installationGuideButton)
			.then(async selection => {
				try {
					if (selection === selfHealingMessages.installPluginButton) {
						await vscode.commands.executeCommand(commands.installCxDevAssistPlugin);
					} else if (selection === selfHealingMessages.installationGuideButton) {
						await vscode.env.openExternal(vscode.Uri.parse(DOC_LINKS.copilotCliPluginUrl));
					}
				} catch (error) {
					logs?.warn(`Self-Healing install action failed: ${error instanceof Error ? error.message : String(error)}`);
				}
			});
	} catch (error) {
		logs?.warn(`Self-Healing turn-on check failed: ${error instanceof Error ? error.message : String(error)}`);
	}
}

export interface CopilotCliResult {
	ok: boolean;
	output: string;
}

export interface CopilotCliDeps {
	find: () => string | undefined | Promise<string | undefined>;
	run: (exe: string, args: string[], timeoutMs?: number) => Promise<CopilotCliResult>;
	/** Installs the Copilot CLI when it is missing; the installed CLI, or undefined. */
	installCli?: () => Promise<string | undefined>;
}

function isFile(filePath: string): boolean {
	try {
		return fs.statSync(filePath).isFile();
	} catch {
		return false;
	}
}

/** <folder>/bin/copilot-shim for appRoot and up to four folders above it. */
function getVsCodeCopilotShimDirs(appRoot: string | undefined): string[] {
	const dirs: string[] = [];
	let dir = appRoot;
	for (let i = 0; dir && i < 5; i++) {
		dirs.push(path.join(dir, "bin", "copilot-shim"));
		const parent = path.dirname(dir);
		dir = parent === dir ? undefined : parent;
	}
	return dirs;
}

/**
 * The GitHub Copilot CLI: `copilot` on PATH, else the shim VS Code ships in <install>/bin/copilot-shim,
 * a few folders above vscode.env.appRoot. On Windows copilot.exe is preferred over npm's copilot.cmd.
 */
export function findCopilotCli(
	envPath: string = process.env.PATH ?? "",
	appRoot: string | undefined = vscode.env?.appRoot,
	platform: NodeJS.Platform = process.platform
): string | undefined {
	const names = platform === "win32" ? ["copilot.exe", "copilot.cmd"] : ["copilot"];
	const dirs = [...envPath.split(path.delimiter).filter(Boolean), ...getVsCodeCopilotShimDirs(appRoot)];
	for (const d of dirs) {
		for (const name of names) {
			const candidate = path.join(d, name);
			if (isFile(candidate)) {
				return candidate;
			}
		}
	}
	return undefined;
}

/** Runs the Copilot CLI with fixed arguments and no input. Never rejects. */
export function runCopilotCli(exe: string, args: string[], timeoutMs = 120000): Promise<CopilotCliResult> {
	// A .cmd (npm's copilot.cmd) only runs through the shell; the arguments are constants
	const viaShell = /\.(cmd|bat)$/i.test(exe);
	return new Promise(resolve => {
		try {
			const child = execFile(
				viaShell ? `"${exe}"` : exe,
				args,
				{ shell: viaShell, windowsHide: true, timeout: timeoutMs },
				(error, stdout, stderr) => {
					const output = `${stdout ?? ""}${stderr ?? ""}`.trim();
					resolve({ ok: !error, output: output || (error ? error.message : "") });
				}
			);
			child.stdin?.end();
		} catch (error) {
			resolve({ ok: false, output: error instanceof Error ? error.message : String(error) });
		}
	});
}

/** True for the copilot launcher VS Code ships in <install>/bin/copilot-shim. */
export function isVsCodeCopilotShim(exe: string): boolean {
	return path.basename(path.dirname(exe)).toLowerCase() === "copilot-shim";
}

/** The key=value lines of a `copilot --vscode-shim` result file ([section] lines are skipped). */
export function parseCopilotShimResult(output: string): Map<string, string> {
	const values = new Map<string, string>();
	for (const line of output.split(/\r?\n/)) {
		const index = line.indexOf("=");
		if (index > 0) {
			values.set(line.slice(0, index).trim(), line.slice(index + 1).trim());
		}
	}
	return values;
}

/** The real CLI from `copilot --vscode-shim probe` output: cliPath when cliFound=1. */
export function parseCopilotShimProbe(output: string): string | undefined {
	const values = parseCopilotShimResult(output);
	const cliPath = values.get("cliPath");
	return values.get("cliFound") === "1" && cliPath ? cliPath : undefined;
}

/**
 * Runs `copilot --vscode-shim <args> --result-file <temp file>`. The result file's text, or undefined when the
 * shim wrote none (an older shim without these subcommands).
 */
async function runCopilotShim(
	shim: string,
	args: string[],
	run: CopilotCliDeps["run"],
	timeoutMs?: number
): Promise<{ result: CopilotCliResult; text?: string }> {
	const resultFile = path.join(os.tmpdir(), `cx-copilot-shim-${args[0]}-${process.pid}-${Date.now()}.txt`);
	try {
		const result = await run(shim, ["--vscode-shim", ...args, "--result-file", resultFile], timeoutMs);
		return { result, text: isFile(resultFile) ? fs.readFileSync(resultFile, "utf8") : undefined };
	} finally {
		fs.rmSync(resultFile, { force: true });
	}
}

/**
 * The Copilot CLI to install with. The VS Code shim is only a launcher: with no real CLI behind it, it asks in
 * a terminal to install one, so it is resolved with `copilot --vscode-shim probe`. The real CLI it reports is
 * used; undefined when it reports none. An older shim without the probe is kept as before.
 */
export async function resolveCopilotCli(
	found: string | undefined = findCopilotCli(),
	run: CopilotCliDeps["run"] = runCopilotCli
): Promise<string | undefined> {
	if (!found || !isVsCodeCopilotShim(found)) {
		return found;
	}
	const probe = await runCopilotShim(found, ["probe"], run);
	if (probe.text === undefined) {
		currentLogs?.info(`copilot --vscode-shim probe is not available (${probe.result.output}); using ${found}`);
		return found;
	}
	const cliPath = parseCopilotShimProbe(probe.text);
	currentLogs?.info(cliPath ? `The VS Code Copilot shim reports the GitHub Copilot CLI at ${cliPath}` : "The VS Code Copilot shim reports no GitHub Copilot CLI");
	return cliPath;
}

const defaultCopilotCliDeps: CopilotCliDeps = {
	find: () => resolveCopilotCli(),
	run: runCopilotCli,
};
let copilotCliDeps = defaultCopilotCliDeps;

/** For tests only: replaces how the Copilot CLI is found and run (undefined restores the default). */
export function setCopilotCliDeps(deps?: CopilotCliDeps): void {
	copilotCliDeps = deps ?? defaultCopilotCliDeps;
}

/** copilot plugin marketplace add ..., then copilot plugin install ...; the install result decides. */
async function installWithCopilotCli(cli: string): Promise<CopilotCliResult> {
	const [addArgs, installArgs] = constants.cxDevAssistPluginCliInstallArgs;
	const added = await copilotCliDeps.run(cli, addArgs);
	if (!added.ok) {
		// Usually the marketplace is already added; the install below reports any real problem
		currentLogs?.info(`copilot ${addArgs.join(" ")}: ${added.output}`);
	}
	return copilotCliDeps.run(cli, installArgs);
}

/** "...is already installed: Copilot CLI (<folder>)." or "...is already installed." */
export function alreadyInstalledMessage(locations: CxDevAssistInstallLocation[]): string {
	return locations.length > 0
		? `${selfHealingMessages.pluginAlreadyInstalled}: ${describeInstallLocations(locations)}.`
		: `${selfHealingMessages.pluginAlreadyInstalled}.`;
}

/** Turns on the Self-Healing setting (application scope, so Global). */
async function enableSelfHealing(): Promise<void> {
	await vscode.workspace
		.getConfiguration(constants.getSelfHealingConfigSection())
		.update(constants.activateSelfHealing, true, vscode.ConfigurationTarget.Global);
}

/**
 * Shows a plugin-installed message followed by the Self-Healing state. No buttons while Self-Healing is on;
 * an Enable Self-Healing button while it is off.
 */
async function showPluginInstalledMessage(baseMessage: string): Promise<void> {
	if (isSelfHealingEnabled()) {
		await vscode.window.showInformationMessage(`${baseMessage} ${selfHealingMessages.selfHealingActive}`);
		return;
	}
	const selection = await vscode.window.showInformationMessage(
		`${baseMessage} ${selfHealingMessages.selfHealingOff}`,
		selfHealingMessages.enableSelfHealingButton
	);
	if (selection === selfHealingMessages.enableSelfHealingButton) {
		await enableSelfHealing();
	}
}

/** The plugin was installed (or reported) by this extension: no second "installed" confirmation from the watchers. */
function markPluginInstalled(): void {
	pluginDetected = true;
	installedConfirmationShown = true;
}

/**
 * Called when a watched plugin file changes: shows the "installed" confirmation once when cx-devassist goes
 * from not detected to detected (installed from VS Code's plugin browser or with the Copilot CLI) while
 * logged in. Never throws.
 */
export async function onPluginDetectionChanged(context: Pick<vscode.ExtensionContext, "globalStorageUri">): Promise<void> {
	try {
		const detected = await isCxDevAssistPluginAvailable({ userDataDir: getVsCodeUserDataDir(context) });
		const wasDetected = pluginDetected;
		pluginDetected = detected;
		if (detected && wasDetected === false && isIdeOnboardingAuthenticated() && !installedConfirmationShown) {
			installedConfirmationShown = true;
			await showPluginInstalledMessage(selfHealingMessages.pluginInstalledDetected);
		}
	} catch (error) {
		currentLogs?.warn(`Self-Healing plugin detection failed: ${error instanceof Error ? error.message : String(error)}`);
	}
}

/**
 * Installs cx-devassist silently, without asking first (VS Code also runs plugins the Copilot CLI installed):
 * an existing install is reported with its location instead of installing again; otherwise it installs with
 * the GitHub Copilot CLI. Without the Copilot CLI it offers to install the CLI with VS Code's copilot shim
 * first. When there is still no CLI, or the CLI install fails, it opens VS Code's plugin browser filtered to
 * cx-devassist (VS Code has no API to install an agent plugin directly). Never throws.
 */
export async function installCxDevAssistPluginInVsCode(context?: Pick<vscode.ExtensionContext, "globalStorageUri">): Promise<void> {
	try {
		if (!isIdeOnboardingAuthenticated()) {
			currentLogs?.info("Cannot install cx-devassist plugin: user not authenticated");
			void vscode.window.showErrorMessage("Failed to install Checkmarx DevAssist. Authentication required.");
			return;
		}
		const locations = await getCxDevAssistInstallLocations({ userDataDir: getVsCodeUserDataDir(context) });
		if (locations.length > 0) {
			currentLogs?.info(alreadyInstalledMessage(locations));
			await showPluginInstalledMessage(selfHealingMessages.pluginAlreadyInstalled);
			return;
		}
		const cli = await copilotCliDeps.find();
		if (!cli) {
			currentLogs?.info("GitHub Copilot CLI not available; showing documentation link for installing cx-devassist");
			const selection = await vscode.window.showInformationMessage(
				"GitHub Copilot CLI Is not available. Install the cx-devassit plugin through vscode setting. Please refer Installation documentation.",
				selfHealingMessages.installationGuideButton
			);
			if (selection === selfHealingMessages.installationGuideButton) {
				await vscode.env.openExternal(vscode.Uri.parse(DOC_LINKS.copilotCliPluginUrl));
			}
			return;
		}
		const result = await vscode.window.withProgress(
			{ location: vscode.ProgressLocation.Notification, title: selfHealingMessages.installingPlugin },
			() => installWithCopilotCli(cli)
		);
		if (result.ok) {
			currentLogs?.info(`Installed the Checkmarx cx-devassist plugin with GitHub Copilot CLI at ${cli}`);
			markPluginInstalled();
			void vscode.window.showInformationMessage(selfHealingMessages.pluginInstalled);
			return;
		}
		if (/already installed/i.test(result.output)) {
			markPluginInstalled();
			await showPluginInstalledMessage(selfHealingMessages.pluginAlreadyInstalled);
			return;
		}
		currentLogs?.error(`${selfHealingMessages.pluginInstallFailed} ${result.output}`);
		currentLogs?.info("Plugin installation failed; showing documentation link for manual installation");
		const selection = await vscode.window.showWarningMessage(
			"Could not install the Checkmarx cx-devassist plugin. Please refer to the installation documentation.",
			selfHealingMessages.installationGuideButton
		);
		if (selection === selfHealingMessages.installationGuideButton) {
			await vscode.env.openExternal(vscode.Uri.parse(DOC_LINKS.copilotCliPluginUrl));
		}
	} catch (error) {
		currentLogs?.error(`${selfHealingMessages.pluginInstallFailed} ${error instanceof Error ? error.message : String(error)}`);
	}
}

/**
 * Checkmarx Self-Healing drives the cx-devassist plugin inside GitHub Copilot in Visual Studio Code
 * (stable and Insiders) only. The same extension also runs in VS Code forks (Cursor, Windsurf, Kiro,
 * Devin, ...), where it must do nothing: above all it must not write the shared
 * ~/.checkmarx/cx-onboarding-ide.properties, or a fork's setting would overwrite the user's VS Code choice.
 */
export function isSelfHealingSupportedHost(appName: string = vscode.env?.appName ?? ""): boolean {
	return appName.toLowerCase().includes(constants.vsCodeAgentOrginalName.toLowerCase());
}

/**
 * Called at the end of a successful login: keeps the user's Self-Healing choice, writes the settings to the
 * file, then evaluates the install messages.
 */
export async function onSelfHealingPostAuth(context: vscode.ExtensionContext, logs?: Logs): Promise<void> {
	if (!isSelfHealingSupportedHost()) {
		return;
	}
	setIdeOnboardingAuthenticated(true);
	syncIdeOnboardingProperties(logs ?? currentLogs);
}

/** Called on logout: the file then says Self-Healing and every scanner are OFF. Never throws. */
export function onSelfHealingLogout(logs?: Logs): void {
	if (!isSelfHealingSupportedHost()) {
		return;
	}
	setIdeOnboardingAuthenticated(false);
	promptArmed = false;
	syncIdeOnboardingProperties(logs ?? currentLogs);
}

/** Logged in when the credential is stored; re-syncs the file. Covers activation and other windows. */
async function syncAuthFromSecrets(context: vscode.ExtensionContext, logs: Logs): Promise<void> {
	let token: string | undefined;
	try {
		token = await context.secrets.get(constants.getAuthCredentialSecretKey());
	} catch (error) {
		logs.warn(`Could not read the Checkmarx credential: ${error instanceof Error ? error.message : String(error)}`);
	}
	setIdeOnboardingAuthenticated(!!token);
	syncIdeOnboardingProperties(logs);
}

function sendSelfHealingTelemetry(enabled: boolean): void {
	try {
		Promise.resolve(
			cx.setUserEventDataForLogs("settings", enabled ? "selfHealingEnabled" : "selfHealingDisabled", "", "")
		).catch(() => undefined);
	} catch {
		// Telemetry is best effort
	}
}

/**
 * Registers the install command, the settings listener and the plugin file watchers
 * (~/.copilot/config.json, ~/.vscode/agent-plugins/installed.json, <user-data>/agentPlugins/cache.json),
 * and writes the properties file once on activation, as logged in or logged out.
 */
export function registerSelfHealing(context: vscode.ExtensionContext, logs: Logs): void {
	currentLogs = logs;
	if (!isSelfHealingSupportedHost()) {
		// VS Code forks: only the command declared in package.json, explaining it is VS Code only. No
		// file write, listeners, watchers, install messages or telemetry.
		context.subscriptions.push(
			vscode.commands.registerCommand(commands.installCxDevAssistPlugin, () =>
				vscode.window.showInformationMessage(selfHealingMessages.vsCodeOnly)
			)
		);
		return;
	}
	try {
		registerSelfHealingListeners(context, logs);
	} catch (error) {
		logs.error(`Failed to register Checkmarx Self-Healing: ${error instanceof Error ? error.message : String(error)}`);
	}
	void syncAuthFromSecrets(context, logs);
}

function registerSelfHealingListeners(context: vscode.ExtensionContext, logs: Logs): void {
	context.subscriptions.push(
		vscode.commands.registerCommand(commands.installCxDevAssistPlugin, () => installCxDevAssistPluginInVsCode(context))
	);

	context.subscriptions.push(
		vscode.workspace.onDidChangeConfiguration(event => {
			const keys = getIdeOnboardingConfigKeys();
			if (!keys.some(key => event.affectsConfiguration(key))) {
				return;
			}
			syncIdeOnboardingProperties(logs);
			if (event.affectsConfiguration(keys[0])) {
				const enabled = isSelfHealingEnabled();
				sendSelfHealingTelemetry(enabled);
				if (enabled) {
					promptArmed = true;
					void onSelfHealingTurnedOn(context, logs);
				}
			}
		})
	);

	context.subscriptions.push(
		context.secrets.onDidChange(event => {
			if (event.key === constants.getAuthCredentialSecretKey()) {
				void syncAuthFromSecrets(context, logs);
			}
		})
	);

	void isCxDevAssistPluginAvailable({ userDataDir: getVsCodeUserDataDir(context) }).then(detected => {
		pluginDetected = detected;
	});
	const listener = () => {
		void onPluginDetectionChanged(context);
		if (promptArmed) {
			void maybeShowSelfHealingPrompt(context);
		}
	};
	for (const watchPath of getPluginDetectionWatchPaths(context)) {
		try {
			fs.watchFile(watchPath, { interval: 5000, persistent: false }, listener);
			context.subscriptions.push({ dispose: () => fs.unwatchFile(watchPath, listener) });
		} catch (error) {
			logs.warn(`Failed to watch ${watchPath}: ${error instanceof Error ? error.message : String(error)}`);
		}
	}
}

/** For tests only. */
export function resetSelfHealingSessionState(): void {
	shownThisSession = false;
	promptArmed = false;
	setIdeOnboardingAuthenticated(false);
	pluginDetected = undefined;
	installedConfirmationShown = false;
}

/** For tests only: the last plugin detection result, as seen at registration or by the file watchers. */
export function setPluginDetectedForTests(value: boolean | undefined): void {
	pluginDetected = value;
}
